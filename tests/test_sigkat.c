static void hashes(void)
{
	unsigned char h[64];
	br_sha1_context c1;
	br_sha256_context c256;
	br_sha384_context c384;
	br_sha512_context c512;

	br_sha1_init(&c1);
	br_sha1_update(&c1, "abc", 3);
	br_sha1_out(&c1, h);
	check("SHA-1(abc)", memcmp(h, ABC_SHA1, 20) == 0);
	br_sha256_init(&c256);
	br_sha256_update(&c256, "abc", 3);
	br_sha256_out(&c256, h);
	check("SHA-256(abc)", memcmp(h, ABC_SHA256, 32) == 0);
	br_sha384_init(&c384);
	br_sha384_update(&c384, "abc", 3);
	br_sha384_out(&c384, h);
	check("SHA-384(abc)", memcmp(h, ABC_SHA384, 48) == 0);
	if (memcmp(h, ABC_SHA384, 48) != 0)
		hexout("got", h, 48);
	br_sha512_init(&c512);
	br_sha512_update(&c512, "abc", 3);
	br_sha512_out(&c512, h);
	check("SHA-512(abc)", memcmp(h, ABC_SHA512, 64) == 0);
}

static void rsa(void)
{
	unsigned char b[256];
	static const unsigned char e[3] = { 0x01, 0x00, 0x01 };
	br_rsa_public_key pk;

	memcpy(b, RSA_X, sizeof b);
	check("RSA-2048 x^e mod n: sig_rsa",
		sig_rsa(b, sizeof b, RSA_N, sizeof RSA_N, e, sizeof e)
		&& memcmp(b, RSA_Y, sizeof b) == 0);
	if (memcmp(b, RSA_Y, sizeof b) != 0)
		hexout("got", b, 32);
	pk.n = (unsigned char *)RSA_N;
	pk.nlen = sizeof RSA_N;
	pk.e = (unsigned char *)e;
	pk.elen = sizeof e;
	memcpy(b, RSA_X, sizeof b);
	check("RSA-2048 x^e mod n: br_rsa_i15_public",
		br_rsa_i15_public(b, sizeof b, &pk) && memcmp(b, RSA_Y, sizeof b) == 0);
}

static void ecdsa(const char *what, int curve, const unsigned char *q, size_t qlen,
	const br_hash_class *hc, const unsigned char *sig, size_t slen)
{
	br_hash_compat_context c;
	br_ec_public_key pk;
	unsigned char h[64], bad[132];
	size_t hlen = (hc->desc >> BR_HASHDESC_OUT_OFF) & BR_HASHDESC_OUT_MASK;
	char line[80];

	hc->init(&c.vtable);
	hc->update(&c.vtable, "sample", 6);
	hc->out(&c.vtable, h);
	pk.curve = curve;
	pk.q = (unsigned char *)q;
	pk.qlen = qlen;
	sprintf(line, "%s: ecvrfy", what);
	check(line, ecvrfy_raw(&br_ec_all_m15, h, hlen, &pk, sig, slen) == 1);
	sprintf(line, "%s: br_ecdsa_i15", what);
	check(line, br_ecdsa_i15_vrfy_raw(&br_ec_all_m15, h, hlen, &pk, sig, slen) == 1);
	sprintf(line, "%s: br_ecdsa_i15 on prime_i15", what);
	check(line, br_ecdsa_i15_vrfy_raw(&br_ec_prime_i15, h, hlen, &pk, sig, slen) == 1);
	memcpy(bad, sig, slen);
	bad[slen - 1] ^= 1;
	sprintf(line, "%s, s changed: rejected by both", what);
	check(line, ecvrfy_raw(&br_ec_all_m15, h, hlen, &pk, bad, slen) == 0
		&& br_ecdsa_i15_vrfy_raw(&br_ec_all_m15, h, hlen, &pk, bad, slen) == 0);
}

