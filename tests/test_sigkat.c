static int fails;

static void check(const char *what, int ok)
{
	printf("  %-44s %s\n", what, ok ? "ok" : "FAILED");
	if (!ok)
		fails++;
}

static void hexout(const char *what, const unsigned char *b, size_t n)
{
	size_t i;

	printf("    %s: ", what);
	for (i = 0; i < n; i++)
		printf("%02x", b[i]);
	printf("\n");
}
